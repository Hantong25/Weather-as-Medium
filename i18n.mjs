const keys = Object.keys(english).sort((a,b) => b.length-a.length);
export function translate(value, useEnglish = true) {
 const text = String(value ?? ''); if (!useEnglish) return text;
 if (Object.hasOwn(english, text)) return english[text];
 let result = text;
 for (const [pattern, replacement] of rules) result = result.replace(pattern, replacement);
 for (const key of keys) if (result.includes(key)) result = result.replaceAll(key, english[key]);
 return result;
}
export const isEnglish = typeof document !== 'undefined' && document.documentElement.lang.startsWith('en');
export const tr = value => translate(value, isEnglish);
